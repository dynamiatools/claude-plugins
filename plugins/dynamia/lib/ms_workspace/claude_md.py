"""Generate the managed block of <workspace>/CLAUDE.md (user text outside the markers is never touched)."""
from __future__ import annotations

import shutil

from .core import Workspace, die, topo

BEGIN = "<!-- ms-workspace:begin (generated by `ms-workspace claude-md`; edit outside this block) -->"
END = "<!-- ms-workspace:end -->"

TOOL_LABELS = {
    "idea": "IDE tools (`mcp__idea__*`) when available",
    "codebase-memory": "codebase-memory graph tools for structure, callers and impact",
    "grep": "Grep/Glob/Read (never block on a missing tool)",
}


def _tool_label(name: str) -> str:
    if name in TOOL_LABELS:
        return TOOL_LABELS[name]
    if name.startswith("mcp:"):
        return f"`mcp__{name[4:]}__*` tools when available"
    return name


def default_discovery() -> list[str]:
    """Without [tools] discovery, recommend only what is installed here: the graph when its binary is on PATH, then plain search.
    The IDE tools are never assumed: the CLI cannot see an MCP connection, so they appear only when the user lists them."""
    return (["codebase-memory"] if shutil.which("codebase-memory-mcp") else []) + ["grep"]


def render(ws: Workspace) -> str:
    name = ws.get("name", default="unnamed")
    tasks = ws.get("tasks", default="local")
    out = [BEGIN, f"# Workspace: {name}", "",
           "Multi-repo workspace. Each repo keeps its own CLAUDE.md; follow it for code conventions.", "",
           "## Repos (dependency order)"]
    for r in topo(ws, ws.repo_names()):
        c = ws.repo_cfg(r)
        stacks = "+".join(c.get("stacks") or []) or "no stack detected"
        deps = c.get("deps") or []
        out.append(f"- {r}: base `{c.get('base') or 'main'}`, {stacks}, push {c.get('push') or 'direct'}"
                   + (f", depends on {', '.join(deps)}" if deps else ""))
    out += ["", "## Rules for agents",
            "- Work only inside the repo/module assigned to your task, inside a batch worktree (`working-trees/<batch>/...`, or `.batches/<batch>/...` in an older layout).",
            "- Commit locally. Never `git push`, `gh pr create|merge` or `ms-workspace clean --force|undo` by hand: a hook blocks them. "
            "Publishing goes through `/dynamia:ship` (plan, confirmation, `ms-workspace ship`), and only when the user asks: "
            "\"open a PR\" means `ship --pr`; \"ship\" or \"publish\" uses each repo's configured push mode. If the plan says RECOMMEND A PR, tell the user and let them choose.",
            "- Missing dependencies: run `ms-workspace env <batch> --setup` (the repo's own `setup` command; Claude Code asks the user to approve it). If the repo has none, use its normal install command (npm/pnpm/mvn/gradle) in the worktree. Only `env --trust` is left to the user.",
            "- After changes run `ms-workspace test t0` (tests only what changed). Fix failures before saying you are done.",
            "- Never create worktrees by hand; use `ms-workspace batch new` / `agent new`. /dynamia:batch recommends a worktree or a plain local branch in the repo and asks the user to choose "
            "(worktree recommended when the repo is not on its base branch or the task is new; a plain branch only for a small, single-repo task on a clean checkout).",
            "- Before starting a task or session run `ms-workspace usage --check` (add `--need <pct>` with your estimate of the 5h-window share the task needs). "
            "Exit 1 or 2: show the numbers and get the user's confirmation first. Exit 3: no data, proceed. "
            "Never leave work half done: prefer finishing or cleanly stopping a small step.",
            "- To check an API use `ms-workspace http run <file> --env local` (requests live in `requests/*.http.toml`; assertions and a masked log of every exchange are built in). "
            "Never put tokens in request files: use `{{secret:NAME}}`.",
            "- `ms-workspace gate` scans what would be sent for secrets and leftovers (ship runs it); `ms-workspace recall <words>` searches past sessions, notes and the log; "
            "a handoff note is written automatically before compaction and at the end of a session.",
            "- Save durable facts with `ms-workspace memory add --type gotcha|decision|lesson \"...\"` (why, not just what). "
            "If you must stop before finishing (usage critical, interrupted), leave a handoff: "
            "`ms-workspace memory add --type handoff --batch <batch> \"state, next step, files touched\"`.",
            "", "## Batch flow (human-driven)",
            "`batch new` -> `agent new` -> `test t0` -> `integrate` -> `test t1` -> `ship --yes` (or `--pr`) -> `clean`.",
            "Skills: /dynamia:batch, /dynamia:integrate, /dynamia:ship.",
            "", "## Saving tokens",
            "- One agent by default; parallel agents only for independent repos or modules.",
            "- Read `ms-workspace context`, `status` and `log` before exploring the repos.",
            "- Images pasted in chat are archived under `images/` in the workspace folder (`.ms-workspace/images/` in an older layout); `ms-workspace images` lists recent ones "
            "(path plus the text sent with them), so you can look at an earlier screenshot with Read instead of asking for it again.",
            "- Hooks shorten huge Bash output (the full text is saved to a file they name) and warn when you re-read an unchanged file: "
            "narrow commands (grep, head, the failing test only) and reuse what is already in context.",
            "- Delegate code search to `dynamia:scout`, failing-test analysis to `dynamia:test-triage`, "
            "summaries and commit drafts to `dynamia:summarizer` (all Haiku).",
            "", "## Tool preference"]
    discovery = ws.get("tools", "discovery", default=default_discovery())
    out += [f"{i}. {_tool_label(t)}" for i, t in enumerate(discovery, 1)]
    if ws.get("tools", "shell", default="rtk") == "rtk":
        out.append("Shell output is filtered by `rtk` when it is installed.")
    if ws.get("tools", "notes"):
        out.append(ws.get("tools", "notes"))
    out += ["", "## Tasks",
            f"Tracking mode: `{tasks}` (`local` = TASKS.md inside each batch; `github` = GitHub issues, "
            "one tracking issue per batch; `ask` = ask the user where to keep the tasks and confirm before creating any local task file). "
            "A repo can override it with `tasks` in workspace.toml.",
            "If the DynamiaTasks MCP (`mcp__dynamia-tasks__*` tools, from dynamiatools/dynamia-tasks, still in development) is available, "
            "use it to read and update tasks instead of editing TASKS.md or calling `gh` by hand: it manages the local tasks "
            "(`.dynamia/tasks`: backlog.json, comments.json, workspace.json) and can add a task to the workspace through a connector (local or GitHub issues). "
            "Without it, nothing changes."]
    overrides = [f"- {r}: {ws.repo_cfg(r)['tasks']}" for r in ws.repo_names()
                 if ws.repo_cfg(r).get("tasks") not in (None, tasks)]
    if overrides:
        out += ["Per-repo overrides:", *overrides]
    out.append(END)
    return "\n".join(out) + "\n"


def cmd_claude_md(ws: Workspace, args: list[str]) -> int:
    block = render(ws)
    if args[:1] == ["--print"]:
        print(block, end="")
        return 0
    target = ws.project / "CLAUDE.md"
    if "--refresh" in args:
        # For tool installs: rewrite only a file that is entirely our block; anything with user text (or no file) stays as it is.
        text = target.read_text() if target.is_file() else ""
        if not (text.startswith(BEGIN) and text.rstrip("\n").endswith(END) and text.count(BEGIN) == 1):
            print(f"{target} is not a generated file: left untouched.")
            return 0
        target.write_text(block)
        print(f"Refreshed {target}")
        return 0
    if target.exists():
        text = target.read_text()
        if BEGIN not in text and "--append" not in args:
            print(f"{target} already exists and is yours: left untouched.\n"
                  "Run with --print to see the block, or with --append to add it at the end (everything above it stays).")
            return 3
        if BEGIN in text:
            head, _, rest = text.partition(BEGIN)
            if END not in rest:
                die(f"{target} has a managed block start without an end marker; fix it by hand")
            tail = rest.partition(END)[2]
            new = head + block.rstrip("\n") + tail
            msg = f"Updated managed block in {target}"
        else:
            new = text + ("" if text.endswith("\n") else "\n") + "\n" + block
            msg = f"Appended managed block to existing {target}"
    else:
        new, msg = block, f"Created {target}"
    target.write_text(new)
    print(msg)
    ws.log("claude-md", "ok", "", "", str(target))
    return 0
